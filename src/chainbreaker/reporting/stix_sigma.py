from __future__ import annotations

import json
from datetime import datetime, timezone
from uuid import uuid4
from typing import Any


def export_stix_bundle(run_id: str, report: dict[str, Any]) -> dict[str, Any]:
    """Export incident evidence and attack chain as a standards-compliant STIX 2.1 JSON bundle."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%fZ")
    bundle_id = f"bundle--{uuid4()}"
    identity_id = f"identity--{uuid4()}"
    actor_id = f"threat-actor--{uuid4()}"

    objects = [
        {
            "type": "identity",
            "spec_version": "2.1",
            "id": identity_id,
            "created": now,
            "modified": now,
            "name": "ChainBreaker Municipal Cyber Defense Unit",
            "identity_class": "organization",
            "sectors": ["government-local", "transportation", "energy"],
        },
        {
            "type": "threat-actor",
            "spec_version": "2.1",
            "id": actor_id,
            "created": now,
            "modified": now,
            "name": f"Adversary - {run_id}",
            "threat_actor_types": ["hostile-intruder", "infrastructure-disruption"],
            "description": f"Inferred attack chain traversing authentication, gateway, and IoT controllers in run {run_id}.",
            "sophistication": "intermediate",
            "resource_level": "organization",
        },
    ]

    # Map findings into STIX indicators
    findings = report.get("findings", [])
    for idx, finding in enumerate(findings[:12]):
        ind_id = f"indicator--{uuid4()}"
        rule_id = finding.get("rule_id", "ANOMALY")
        stage = finding.get("stage", "initial-access")
        explanation = finding.get("explanation", "Detected anomaly")
        features = finding.get("features", {})
        
        # Build pattern expression
        pattern = f"[file:name = '{rule_id}']"
        if "source_ip" in features:
            pattern = f"[ipv4-addr:value = '{features['source_ip']}']"
        elif "domain" in features:
            pattern = f"[domain-name:value = '{features['domain']}']"

        objects.append({
            "type": "indicator",
            "spec_version": "2.1",
            "id": ind_id,
            "created": now,
            "modified": now,
            "name": f"{rule_id}: {finding.get('title', 'Detection Indicator')}",
            "description": explanation,
            "indicator_types": ["malicious-activity", "anomalous-activity"],
            "pattern": pattern,
            "pattern_type": "stix",
            "valid_from": now,
            "kill_chain_phases": [
                {
                    "kill_chain_name": "mitre-attack",
                    "phase_name": str(stage).lower().replace(" ", "-"),
                }
            ],
        })

        # Relate indicator to threat actor
        objects.append({
            "type": "relationship",
            "spec_version": "2.1",
            "id": f"relationship--{uuid4()}",
            "created": now,
            "modified": now,
            "relationship_type": "indicates",
            "source_ref": ind_id,
            "target_ref": actor_id,
        })

    return {
        "type": "bundle",
        "id": bundle_id,
        "objects": objects,
    }


def export_sigma_rules(run_id: str, findings: list[dict[str, Any]]) -> str:
    """Generate YAML Sigma rules from detected incident patterns for SIEM import (Wazuh, Splunk, Elastic)."""
    rules: list[str] = []
    seen_rules = set()

    for finding in findings:
        rule_id = finding.get("rule_id", "GENERIC-ANOMALY")
        if rule_id in seen_rules:
            continue
        seen_rules.add(rule_id)

        severity = finding.get("severity", "medium").lower()
        title = finding.get("title", f"Detect {rule_id}")
        explanation = finding.get("explanation", "ChainBreaker anomaly detection rule")
        stage = str(finding.get("stage", "initial_access")).lower().replace("-", "_")

        rule_yaml = f"""# Sigma Rule generated by ChainBreaker Defense Platform
title: ChainBreaker {rule_id} - {title}
id: {uuid4()}
status: experimental
description: {explanation}
references:
    - https://github.com/kumarraunak20060911-svg/chainbreaker
author: ChainBreaker Autonomous Engine
date: {datetime.now(timezone.utc).strftime("%Y/%m/%d")}
tags:
    - attack.{stage}
logsource:
    category: application
    product: smart_city_telemetry
detection:
    selection:
        detector_rule: '{rule_id}'
        finding_severity: '{severity}'
    condition: selection
falsepositives:
    - Authorized maintenance windows
    - Vendor diagnostics with approved change request
level: {severity}
---"""
        rules.append(rule_yaml)

    return "\n\n".join(rules) if rules else "# No findings to generate Sigma rules"
